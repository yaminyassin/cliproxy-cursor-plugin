// executor (chat-completions <-> Cursor Connect/gRPC translation), and
// model_registrar/model_provider (dynamic Cursor model discovery). The
// actual capability implementations live in internal/dispatch and the
// capability packages it wires together (internal/account, internal/auth,
// internal/executor, internal/discovery).
